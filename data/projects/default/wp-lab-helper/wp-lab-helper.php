// Public preview support for temporary WP Lab tunnels.
function wp_lab_is_public_preview_request(){
  $host = strtolower($_SERVER['HTTP_HOST'] ?? '');
  return $host && $host !== 'localhost:8085' && $host !== '127.0.0.1:8085' && !str_starts_with($host,'localhost') && !str_starts_with($host,'127.0.0.1');
}
add_filter('pre_option_home', function($v){
  if(wp_lab_is_public_preview_request()){
    $scheme = (!empty($_SERVER['HTTP_X_FORWARDED_PROTO']) ? sanitize_text_field($_SERVER['HTTP_X_FORWARDED_PROTO']) : 'https');
    return $scheme.'://'.sanitize_text_field($_SERVER['HTTP_HOST']);
  }
  return $v;
});
add_filter('pre_option_siteurl', function($v){
  if(wp_lab_is_public_preview_request()){
    $scheme = (!empty($_SERVER['HTTP_X_FORWARDED_PROTO']) ? sanitize_text_field($_SERVER['HTTP_X_FORWARDED_PROTO']) : 'https');
    return $scheme.'://'.sanitize_text_field($_SERVER['HTTP_HOST']);
  }
  return $v;
});
add_action('init', function(){
  if(!wp_lab_is_public_preview_request()) return;
  $uri = $_SERVER['REQUEST_URI'] ?? '/';
  if(str_starts_with($uri,'/wp-admin') || str_starts_with($uri,'/wp-login.php')){
    status_header(403);
    nocache_headers();
    wp_die('WP Admin is disabled on this temporary client preview link.','WP Lab Preview',['response'=>403]);
  }
}, 0);
